# Writes ItemTightBounds.cs: the true (vertex-tight) bounds of the items whose meshes the game keeps on the GPU only, so the game
# cannot read their vertices and measures them by the box around each part's turned box (a mesh authored 2-33 degrees off the
# item root measures too big and off-centre: ShieldBanded 1.34 m instead of 0.95). Input: the models session's table, measured
# from the game's own asset bundle (work/storehouse-0.5/item-sizes-fix-20261027/item-tight-bounds-20261027.json, 27 Oct 2026).
# Only kinds with an unreadable part whose tight bounds differ from the box by more than 0.5 mm; readable meshes are measured in
# game from their vertices. Both boxes in ItemVisual's turned item space, root scale not applied (as ItemVisual.Bounds).
#   python tight-table.py <item-tight-bounds.json>
import hashlib
import json
import sys

src = sys.argv[1]
raw = open(src, "rb").read()
table = json.loads(raw)
rows = []
for r in table["kinds"]:
    if r["all_readable"]:
        continue
    t, b = r["tight_turned"], r["box_turned"]
    if max(abs(x - y) for k in ("min", "max") for x, y in zip(t[k], b[k])) <= 0.0005:
        continue
    rows.append((r["prefab"], b["min"], b["max"], t["min"], t["max"]))
rows.sort()

def v(a):
    return "new Vector3(" + ", ".join(f"{x:.4f}f" for x in a) + ")"

out = [
    "// Generated by tight-table.py from " + src.replace("\\", "/").split("/")[-1] + f" (sha256 {hashlib.sha256(raw).hexdigest()[:12]}); do not edit.",
    "// Per item prefab: the game's box (to check the mesh is still the one measured) and the item's true bounds, turned item space.",
    "using System.Collections.Generic;",
    "using UnityEngine;",
    "",
    "namespace Finn.Storehouse;",
    "",
    "static class ItemTightBounds",
    "{",
    "    public static readonly Dictionary<string, (Vector3 boxMin, Vector3 boxMax, Vector3 min, Vector3 max)> Rows = new()",
    "    {",
]
for name, bmin, bmax, tmin, tmax in rows:
    out.append(f'        ["{name}"] = ({v(bmin)}, {v(bmax)}, {v(tmin)}, {v(tmax)}),')
out += ["    };", "}", ""]
open("ItemTightBounds.cs", "w", newline="\n").write("\n".join(out))
print(f"ItemTightBounds.cs: {len(rows)} item(s) from {len(table['kinds'])} measured")
